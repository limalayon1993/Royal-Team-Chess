
-- Create Club Messages Table
create table if not exists club_messages (
    id bigint generated by default as identity primary key,
    club_id uuid references clubs(id) on delete cascade not null,
    sender_id uuid references profiles(id) on delete set null,
    content text not null,
    created_at timestamptz default now()
);

-- Policy to allow members to read messages
alter table club_messages enable row level security;

create policy "Club members can view messages"
on club_messages for select
using (
    auth.uid() in (
        select user_id from club_members where club_id = club_messages.club_id
    )
);

-- Policy to allow members to insert messages
create policy "Club members can insert messages"
on club_messages for insert
with check (
    auth.uid() = sender_id
    and auth.uid() in (
        select user_id from club_members where club_id = club_messages.club_id
    )
);

-- Realtime
alter publication supabase_realtime add table club_messages;
